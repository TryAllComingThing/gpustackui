#!/usr/bin/env python3
"""Generate GPUStack runtime theme CSS from the SaaS V1.1 theme dictionaries.

This is a build-time token compiler only. Theme switching remains in
src/theme/theme.manager.ts; the generated files expose the existing --gp- API
plus per-theme radius and full data visualization palettes.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/theme/tokens/themes"
TARGET = ROOT / "src/theme/styles/themes"
VISUAL = ROOT / "src/theme/tokens/visual-foundation.json"
THEMES = {"standard": "E", "business": "A2", "future": "D", "sky": "B", "ocean": "C"}


def emit(data: dict, theme: str, design_id: str, visual: dict) -> str:
    lines = [
        f"/* GENERATED by scripts/generate_theme_css.py from SaaS theme {design_id}. */",
        f':root[data-theme="{theme}"] {{',
    ]
    brand = {"primary": "g600", "hover": "g500", "pressed": "g900", "accent": "g400", "light": "g300", "subtle": "g100"}
    for source, suffix in brand.items():
        lines.append(f"  --gp-brand-{suffix}: {data['brand'][source]};")
    for group in ("success", "warning", "danger", "info"):
        for source, suffix in (("default", "default"), ("pressed", "pressed"), ("hover", "hover"), ("light", "light"), ("background", "bg")):
            lines.append(f"  --gp-{group}-{suffix}: {data[group][source]};")
    for source, suffix in (("primary", "n900"), ("secondary", "n800"), ("tertiary", "n600"), ("muted", "n500"), ("disabled", "n400")):
        lines.append(f"  --gp-text-{suffix}: {data['text'][source]};")
    for source, suffix in (("default", "n300"), ("divider", "n250"), ("subtle", "n200")):
        lines.append(f"  --gp-line-{suffix}: {data['border'][source]};")
    for source, suffix in (("disabled", "disabled"), ("canvas", "n150"), ("subtle", "n100")):
        lines.append(f"  --gp-background-{suffix}: {data['background'][source]};")
    lines.append(f"  --gp-surface-white: {data['background']['default']};")
    for tone in ("black", "white"):
        for opacity in ("90", "60", "30", "10", "5"):
            lines.append(f"  --gp-alpha-{tone}-{opacity}: {data['alpha'][tone][opacity]};")
    lines += [
        "  --gp-header-bg: var(--gp-brand-g600);",
        "  --gp-header-fg: var(--gp-surface-white);",
        "  --gp-sidebar-bg: var(--gp-brand-g900);",
        "  --gp-sidebar-fg: var(--gp-surface-white);",
        "  --gp-sidebar-hover-bg: var(--gp-brand-g600);",
        "  --gp-sidebar-active-bg: var(--gp-primary-subtle);",
        "  --gp-sidebar-active-fg: var(--gp-brand-g900);",
        "  --gp-sidebar-sub-active-bg: var(--gp-alpha-white-10);",
        "  --gp-sidebar-sub-active-fg: var(--gp-surface-white);",
        "  --gp-page-bg: var(--gp-background-n150);",
        "  --gp-card-bg: var(--gp-surface-white);",
        "  --gp-table-head-bg: var(--gp-background-n100);",
        "  --gp-text-primary: var(--gp-text-n900);",
        "  --gp-text-secondary: var(--gp-text-n800);",
        "  --gp-border-default: var(--gp-line-n300);",
        "  --gp-primary: var(--gp-brand-g600);",
        "  --gp-primary-hover: var(--gp-brand-g500);",
        "  --gp-primary-pressed: var(--gp-brand-g900);",
        "  --gp-primary-subtle: var(--gp-brand-g100);",
        "  --gp-focus-ring: var(--gp-brand-g600);",
        "  --gp-success-fg: var(--gp-success-default);",
        "  --gp-warning-fg: var(--gp-warning-default);",
        "  --gp-danger-fg: var(--gp-danger-default);",
        "  --gp-info-fg: var(--gp-info-default);",
        "  --gp-chart-1: var(--gp-brand-g600);",
        "  --gp-chart-2: var(--gp-info-default);",
        "  --gp-chart-3: var(--gp-success-default);",
        "  --gp-chart-4: var(--gp-warning-default);",
        "  --gp-chart-5: var(--gp-danger-default);",
    ]
    radius = visual["radius"][design_id]
    lines += [
        f"  --gp-radius-sm: {radius['sm']};",
        f"  --gp-radius-md: {radius['md']};",
        f"  --gp-radius-lg: {radius['lg']};",
        f"  --gp-radius-xl: {radius['xl']};",
        "  --gp-radius-tag: var(--gp-radius-sm);",
        "  --gp-radius-control: var(--gp-radius-sm);",
        "  --gp-radius-card: var(--gp-radius-md);",
        "  --gp-radius-dialog: var(--gp-radius-lg);",
    ]
    viz = visual["dataViz"][design_id]
    for index, color in enumerate(viz["categorical6"], 1):
        lines.append(f"  --gp-chart-categorical6-{index}: {color};")
    for index, color in enumerate(viz["categorical12"], 1):
        lines.append(f"  --gp-chart-categorical12-{index}: {color};")
    for index, color in enumerate(viz["sequential5"], 1):
        lines.append(f"  --gp-chart-sequential-{index}: {color};")
    for index, color in enumerate(viz["diverging7"], 1):
        lines.append(f"  --gp-chart-diverging-{index}: {color};")
    for key in ("brand", "success", "warning", "danger", "info"):
        lines.append(f"  --gp-chart-semantic-{key}: {viz['semantic'][key]};")
    for index, color in enumerate(viz["neutral"], 1):
        lines.append(f"  --gp-chart-neutral-{index}: {color};")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated CSS is missing or stale without writing files")
    args = parser.parse_args()

    visual = json.loads(VISUAL.read_text(encoding="utf-8"))
    stale: list[str] = []
    for theme, design_id in THEMES.items():
        source = SOURCE / f"{design_id}.json"
        data = json.loads(source.read_text(encoding="utf-8"))
        target = TARGET / f"{theme}.css"
        rendered = emit(data, theme, design_id, visual)
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != rendered:
                stale.append(str(target.relative_to(ROOT)))
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(rendered, encoding="utf-8")

    if stale:
        print("FAIL: generated theme CSS is missing or stale:", ", ".join(stale), file=sys.stderr)
        print("Run npm run generate:theme-css and commit the generated files.", file=sys.stderr)
        return 1
    if args.check:
        print(f"PASS: {len(THEMES)} generated theme CSS files match their token sources")
        return 0
    print(f"generated {len(THEMES)} theme CSS files from {SOURCE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
