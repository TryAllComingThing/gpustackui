import { test, expect } from '@playwright/test'
test('five themes persist and render components', async ({ page }) => {
 await page.goto('/showcase/index.html')
 await expect(page.getByRole('heading', { name: 'Vue SaaS Design System Showcase' })).toBeVisible()
 await expect(page.getByTestId('showcase-ia-nav')).toBeVisible()
 await expect(page.getByTestId('section-accessibility')).toBeVisible()
 await expect(page.getByTestId('section-quality')).toBeVisible()
 await expect(page.getByTestId('section-user-management')).toBeVisible()
 await expect(page.getByTestId('density-select')).toBeVisible()
 await expect(page.getByLabel('当前主题').locator('option')).toHaveCount(5)
 await expect(page.getByTestId('section-tokens')).toBeVisible()
 await expect(page.getByTestId('section-foundation')).toBeVisible()
 await expect(page.getByTestId('section-f4-states')).toBeVisible()
 await expect(page.getByTestId('state-badge-success')).toBeVisible()
 await expect(page.getByTestId('state-empty')).toBeVisible()
 await expect(page.getByTestId('state-loading')).toBeVisible()
 await expect(page.getByTestId('state-error')).toBeVisible()
 await expect(page.getByTestId('section-matrix').locator('[data-testid^="matrix-"]')).toHaveCount(24)
 const trackedTokens = ['--gp-brand-g600', '--gp-success-default', '--gp-warning-default', '--gp-danger-default']
 const tokenColors = new Map<string, string[]>()
 for (const theme of ['standard','business','future','sky','ocean']) {
   await page.getByLabel('当前主题').selectOption(theme)
   await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
   if (theme === 'standard') {
     await expect(page.getByTestId('button-modal-open')).toHaveCSS('border-top-color', 'rgb(224, 233, 244)')
     await expect(page.getByTestId('button-modal-open')).toHaveCSS('color', 'rgb(32, 43, 61)')
   }
   const colors = await Promise.all(trackedTokens.map((token) => page.locator(`[data-token="${token}"] .swatch-color`).evaluate((swatch) => getComputedStyle(swatch).backgroundColor)))
   const primaryTokens = await page.evaluate(() => {
     const style = getComputedStyle(document.documentElement)
     return {
       uiPrimary: style.getPropertyValue('--ui-primary').trim(),
       gpPrimary: style.getPropertyValue('--gp-primary').trim(),
     }
   })
   expect(primaryTokens.uiPrimary).toBe(primaryTokens.gpPrimary)
   const readableColors = await page.evaluate(() => {
     const nav = document.querySelector('.drp-sidebar-nav')
     const navItem = nav?.querySelector('[data-slot="link"]')
     const breadcrumbCurrent = document.querySelector('.drp-breadcrumb [aria-current="page"]')
     return {
       nav: navItem ? getComputedStyle(navItem).color : '',
       sidebar: nav ? getComputedStyle(nav).color : '',
       breadcrumb: breadcrumbCurrent ? getComputedStyle(breadcrumbCurrent).color : '',
       text: getComputedStyle(document.documentElement).getPropertyValue('--gp-text-primary').trim(),
     }
   })
   expect(readableColors.nav).toBe(readableColors.sidebar)
   expect(readableColors.breadcrumb).not.toBe('')
   await expect.poll(() => page.getByRole('button', { name: '提交表单' }).evaluate((button) => getComputedStyle(button).backgroundColor), { timeout: 1500 }).toBe(colors[0])
   tokenColors.set(theme, colors)
   await page.reload()
   await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
   await expect(page.getByRole('button', { name: /主按钮/ })).toBeVisible()
 }
 await page.getByRole('button', { name: /主按钮/ }).click()
 await expect(page.getByRole('button', { name: /主按钮 · 1/ })).toBeVisible()
 await page.getByRole('button', { name: '打开弹窗' }).click()
 await expect(page.getByText('这是 Nuxt UI 弹窗兼容性验证。')).toBeVisible()
 await expect(page.locator('[role="dialog"]')).toBeVisible()
 await expect(page.locator('[role="dialog"]')).toHaveCSS('position', 'fixed')
 await expect(page.locator('[role="dialog"]')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
 await expect(page.locator('.demo-row .gp-button--primary')).not.toHaveCSS('border-top-style', 'outset')
 await expect(page.locator('#demo-name')).toHaveCSS('border-top-style', 'solid')
 expect(new Set([...tokenColors.values()].map((colors) => colors.join('|'))).size).toBe(5)
})

